// Builds one self-contained file per library Edge Function (supabase/functions/dist/<name>.ts)
// so each can be pasted into the Supabase dashboard editor without the CLI.
// The bundle is the same code as supabase/functions/_shared + <name>/index.ts, concatenated.
// Usage: node tools/bundle_functions.mjs   (then run the wiring tests with TARGET=dist)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';

const FN = new URL('../supabase/functions/', import.meta.url);
const SHARED = ['mp3.ts', 'http.ts', 'library.ts', 'supabase.ts'];
const NPM = "import { createClient } from 'npm:@supabase/supabase-js@2.109.0';";

const strip = (src) => src.split('\n')
  .filter((l) => !/^import\s.*from\s+'\.\.?\//.test(l) && !/^import\s+type\s/.test(l) && l.trim() !== NPM)
  .join('\n');

mkdirSync(new URL('dist/', FN), { recursive: true });
for (const name of ['library-upload', 'library-download', 'library-janitor']) {
  const parts = SHARED.map((f) => `// ---- _shared/${f}\n${strip(readFileSync(new URL(`_shared/${f}`, FN), 'utf8'))}`);
  const index = strip(readFileSync(new URL(`${name}/index.ts`, FN), 'utf8'));
  const body = [NPM, ...parts, `// ---- ${name}/index.ts\n${index}`].join('\n\n');
  const hash = createHash('sha256').update(body).digest('hex').slice(0, 12);
  const out = `// ${name} — GENERATED by tools/bundle_functions.mjs from supabase/functions (do not edit). sha256:${hash}\n${body}`;
  writeFileSync(new URL(`dist/${name}.ts`, FN), out);
  console.log(`dist/${name}.ts  ${out.length} bytes  ${hash}`);
}
